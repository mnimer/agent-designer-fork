/**
 * Python LangGraph Code Generator
 *
 * Purpose:
 * Compiles visual agent workflow documents into production-grade Python LangGraph projects,
 * generating a compliant StateGraph orchestration with TypedDict State, conditional edges,
 * and robust tool bindings.
 *
 * Architectural Decisions:
 * - Author: Mike Nimer <mikenimer@google.com>
 * - Decision 1: Pure Python StateGraph Representation: Translates visual canvas structures
 *   into standard LangGraph StateGraph, using message lists and TypedDict state tracking.
 * - Decision 2: Sanitized Python Identifiers: All agent nodes, routers, tools, and variables
 *   utilize name sanitization to prevent name collision with Python keywords.
 * - Decision 3: Topological Sorting: Guarantees that referenced/sub-graphs and sub-agents
 *   are compiled before parent agents that delegate to them.
 * - Decision 4: Unambiguous entrypoint mapping with `root_agent = ...` assignment.
 */

import { 
  AgentWorkflowDocument, 
  AgentNodeData, 
  ToolDefinition 
} from '../types';
import { GeneratedFile } from './types';
import { ToolAdapterCompiler } from './toolAdapters';
import { pyStr, pyLiteral } from './pythonEscape';
import { sanitizeIdentifier, topologicalSortAgents } from './nameSanitizer';

export interface LanggraphGeneratorOptions {
  includeA2AClient?: boolean;
  defaultModel?: string;
  projectId?: string;
  location?: string;
}

/**
 * Converts an arbitrary identifier string into PascalCase for Python class names.
 *
 * @param str - Input string
 * @returns PascalCase formatted string
 */
export function toPascalCase(str: string): string {
  const words = str
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1));
  return words.join('') || 'Agent';
}

/**
 * LanggraphGenerator compiles visual workflow graphs into Python LangGraph source code.
 */
export class LanggraphGenerator {
  /**
   * Generates complete tools.py file using ToolAdapterCompiler for LangGraph.
   *
   * @param workflow - AgentWorkflowDocument representing the canvas graph
   * @param options - Generator options
   * @returns Complete contents of tools.py
   */
  public generateToolsFile(
    workflow: AgentWorkflowDocument, 
    options?: LanggraphGeneratorOptions
  ): string {
    const agentNodes = (workflow.nodes || []).filter(
      (n) => n.data && (n.data.agentKind === 'standard' || n.data.agentKind === 'router' || n.data.agentKind === 'a2a' || !n.data.agentKind)
    );

    // Sort agents topologically
    const sortedAgents = topologicalSortAgents(agentNodes, workflow.edges || []);

    const idToVar = new Map<string, string>();
    const usedNames = new Set<string>();

    for (const node of sortedAgents) {
      const varName = sanitizeIdentifier(node.data?.label || node.id, usedNames);
      idToVar.set(node.id, varName);
    }

    // Collect standard tools across nodes
    const allTools: ToolDefinition[] = [];
    const seenToolIds = new Set<string>();

    for (const node of workflow.nodes || []) {
      if (node.data && Array.isArray(node.data.tools)) {
        for (const t of node.data.tools) {
          if (!seenToolIds.has(t.id)) {
            seenToolIds.add(t.id);
            allTools.push(t);
          }
        }
      }
    }

    const toolCompiler = new ToolAdapterCompiler();
    const compiledTools = toolCompiler.compile(allTools, 'langgraph');

    const lines: string[] = [
      '"""',
      'tools.py - LangGraph Tools Definition & Registry',
      '',
      'Auto-generated by Visual Agent Designer.',
      'Author: Mike Nimer <mikenimer@google.com>',
      '"""',
      '',
      'import json',
      'import logging',
      'import os',
      'import time',
      'from typing import Any, Dict, List, Optional',
      '',
    ];

    if (compiledTools.imports.length > 0) {
      lines.push(...compiledTools.imports);
      lines.push('');
    }

    lines.push('logger = logging.getLogger(__name__)');
    lines.push('');

    // Standard tool definitions
    if (compiledTools.toolDefinitions.length > 0) {
      lines.push('# ==============================================================================');
      lines.push('# Standard Visual Agent Tools (LangGraph / LangChain)');
      lines.push('# ==============================================================================');
      lines.push(...compiledTools.toolDefinitions);
      lines.push('');
    }

    // Agent Tools Registry
    lines.push('# ==============================================================================');
    lines.push('# Agent Tools Registry & Initializer');
    lines.push('# ==============================================================================');
    lines.push('def setup_agent_tools(agent_id: str) -> List[Any]:');
    lines.push('    """Returns list of executable tools assigned to a given agent id."""');
    lines.push('    tools = []');

    for (const node of sortedAgents) {
      const nodeTools = node.data?.tools || [];
      if (nodeTools.length > 0) {
        lines.push(`    if agent_id == ${pyStr(node.id)}:`);
        for (const t of nodeTools) {
          const varName = sanitizeIdentifier(t.name || t.id);
          lines.push(`        tools.append(${varName})`);
        }
      }
    }

    lines.push('    return tools');
    lines.push('');

    return lines.join('\n');
  }

  /**
   * Generates agent_workflow.py orchestration file for LangGraph.
   *
   * @param workflow - AgentWorkflowDocument representing the canvas graph
   * @param options - Generator options
   * @returns Complete contents of agent_workflow.py
   */
  public generateWorkflowFile(
    workflow: AgentWorkflowDocument, 
    options?: LanggraphGeneratorOptions
  ): string {
    const defaultModel = options?.defaultModel || 'gemini-3.7-flash';
    const agentNodes = (workflow.nodes || []).filter(
      (n) => n.data && (n.data.agentKind === 'standard' || n.data.agentKind === 'router' || n.data.agentKind === 'a2a' || !n.data.agentKind)
    );

    // Sort topologically
    const sortedAgents = topologicalSortAgents(agentNodes, workflow.edges || []);

    const idToVar = new Map<string, string>();
    const usedNames = new Set<string>();

    for (const node of sortedAgents) {
      const varName = sanitizeIdentifier(node.data?.label || node.id, usedNames);
      idToVar.set(node.id, varName);
    }

    const lines: string[] = [
      '"""',
      'agent_workflow.py - LangGraph Workflow Orchestration Engine',
      '',
      'Auto-generated by Visual Agent Designer.',
      'Author: Mike Nimer <mikenimer@google.com>',
      '"""',
      '',
      'import os',
      'import logging',
      'from typing import Any, Dict, List, Optional, TypedDict',
      'from langgraph.graph import StateGraph, START, END',
      'from langchain_google_vertexai import ChatVertexAI',
      'from tools import setup_agent_tools',
      '',
      'logger = logging.getLogger(__name__)',
      '',
      '# ==============================================================================',
      '# State Definition',
      '# ==============================================================================',
      'class AgentState(TypedDict):',
      '    messages: List[Dict[str, Any]]',
      '    current_agent: str',
      '    next_agent: Optional[str]',
      '',
    ];

    // Instantiate Agents/Nodes topologically
    lines.push('# ==============================================================================');
    lines.push('# Initialize Agents & Nodes (Topological Order)');
    lines.push('# ==============================================================================');

    for (const node of sortedAgents) {
      const data = node.data || {};
      const safeVar = idToVar.get(node.id)!;
      const model = data.model || defaultModel;

      if (data.agentKind === 'router') {
        let routerClassName = toPascalCase(data.label || node.id);
        if (!routerClassName.endsWith('Router')) {
          routerClassName += 'Router';
        }

        const branches = data.routerConfig?.branches || [];
        lines.push(`# Router node branches configuration for ${data.label}`);
        lines.push(`${safeVar}_branches = {`);
        for (const branch of branches) {
          let targetVar = 'None';
          if (branch.targetAgentId) {
            targetVar = pyStr(idToVar.get(branch.targetAgentId) || branch.targetAgentId);
          }
          lines.push(`    ${pyStr(branch.id)}: ${targetVar},`);
        }
        lines.push('}');
        lines.push('');

        // Generate node function for router
        lines.push(`def ${safeVar}_node(state: AgentState) -> Dict[str, Any]:`);
        lines.push(`    """Evaluates router logic and returns routing target."""`);
        lines.push(`    logger.info("Evaluating Router: ${data.label}")`);
        lines.push(`    # Evaluate branches matching current state`);
        lines.push(`    next_node = None`);
        for (const branch of branches) {
          const condition = branch.conditionExpression || branch.condition || 'True';
          if (condition !== 'default') {
            lines.push(`    if ${condition}:`);
            lines.push(`        next_node = ${safeVar}_branches.get(${pyStr(branch.id)})`);
          }
        }
        lines.push(`    if next_node is None:`);
        const defaultBranch = branches.find((b) => b.isDefault || b.isDefaultFallback) || branches[branches.length - 1];
        lines.push(`        next_node = ${safeVar}_branches.get(${pyStr(defaultBranch?.id || 'default')})`);
        lines.push(`    return {"next_agent": next_node, "current_agent": ${pyStr(safeVar)}}`);
        lines.push('');
      } else {
        // Standard / A2A Agent Nodes
        lines.push(`# Standard Agent Node: ${data.label}`);
        lines.push(`${safeVar}_llm = ChatVertexAI(model_name=${pyStr(model)})`);
        lines.push(`def ${safeVar}_node(state: AgentState) -> Dict[str, Any]:`);
        lines.push(`    """Invokes agent ${data.label}."""`);
        lines.push(`    logger.info("Invoking Agent: ${data.label}")`);
        lines.push(`    # Bind tools configured for ${data.label}`);
        lines.push(`    tools = setup_agent_tools(${pyStr(node.id)})`);
        lines.push(`    llm_with_tools = ${safeVar}_llm.bind_tools(tools) if tools else ${safeVar}_llm`);
        lines.push(`    response = llm_with_tools.invoke(state["messages"])`);
        lines.push(`    return {`);
        lines.push(`        "messages": state["messages"] + [{"role": "assistant", "content": str(response.content)}],`);
        lines.push(`        "current_agent": ${pyStr(safeVar)},`);
        lines.push(`        "next_agent": None`);
        lines.push(`    }`);
        lines.push('');
      }
    }

    // Build the LangGraph StateGraph workflow
    lines.push('# ==============================================================================');
    lines.push('# Build StateGraph Workflow');
    lines.push('# ==============================================================================');
    lines.push('workflow = StateGraph(AgentState)');
    lines.push('');

    // Add nodes
    lines.push('# Add graph nodes');
    for (const node of sortedAgents) {
      const safeVar = idToVar.get(node.id)!;
      lines.push(`workflow.add_node(${pyStr(safeVar)}, ${safeVar}_node)`);
    }
    lines.push('');

    // Setup entrypoint / start node
    const startNode = sortedAgents.find((n) => n.data?.isStartNode) || sortedAgents[sortedAgents.length - 1];
    const rootVar = startNode ? idToVar.get(startNode.id)! : 'agent';
    lines.push('# Add graph entrypoint');
    lines.push(`workflow.add_edge(START, ${pyStr(rootVar)})`);
    lines.push('');

    // Setup edges
    lines.push('# Add transitions & conditional routing edges');
    for (const node of sortedAgents) {
      const safeVar = idToVar.get(node.id)!;
      const isRouter = node.data?.agentKind === 'router';

      if (isRouter) {
        // Router uses conditional transitions
        lines.push(`def ${safeVar}_router_edge(state: AgentState) -> str:`);
        lines.push(`    return state["next_agent"] if state["next_agent"] else END`);
        lines.push('');
        lines.push(`workflow.add_conditional_edges(${pyStr(safeVar)}, ${safeVar}_router_edge)`);
      } else {
        // Standard edge or fallback to END
        const outgoingEdges = (workflow.edges || []).filter((e) => e.source === node.id);
        if (outgoingEdges.length > 0) {
          for (const edge of outgoingEdges) {
            if (idToVar.has(edge.target)) {
              lines.push(`workflow.add_edge(${pyStr(safeVar)}, ${pyStr(idToVar.get(edge.target)!)})`);
            }
          }
        } else {
          lines.push(`workflow.add_edge(${pyStr(safeVar)}, END)`);
        }
      }
    }
    lines.push('');

    // Unambiguous entrypoint / root agent assignment
    lines.push('# ==============================================================================');
    lines.push('# Entrypoint / Root Agent Assignment');
    lines.push('# ==============================================================================');
    lines.push('root_agent = workflow.compile()');
    lines.push('');

    lines.push('def execute_workflow(user_query: str) -> Dict[str, Any]:');
    lines.push('    """Executes the compiled LangGraph starting from the root agent."""');
    lines.push('    initial_state = {');
    lines.push('        "messages": [{"role": "user", "content": user_query}],');
    lines.push('        "current_agent": "start",');
    lines.push('        "next_agent": None');
    lines.push('    }');
    lines.push('    result = root_agent.invoke(initial_state)');
    lines.push('    last_msg = result["messages"][-1] if result["messages"] else {"content": ""}');
    lines.push('    return {"response": last_msg.get("content", "")}');
    lines.push('');

    return lines.join('\n');
  }

  /**
   * Generates full project repository files for LangGraph.
   *
   * @param workflow - AgentWorkflowDocument
   * @param options - Generator options
   * @returns Array of GeneratedFile items
   */
  public generateFullProject(
    workflow: AgentWorkflowDocument, 
    options?: LanggraphGeneratorOptions
  ): GeneratedFile[] {
    const toolsCode = this.generateToolsFile(workflow, options);
    const workflowCode = this.generateWorkflowFile(workflow, options);

    const requirementsCode = [
      'langgraph>=0.1.0',
      'langchain-core>=0.2.0',
      'langchain-google-vertexai>=1.0.0',
      'google-cloud-aiplatform>=1.70.0',
      'pydantic>=2.0.0',
      'requests>=2.31.0',
    ].join('\n');

    const envCode = [
      '# Google Cloud Project Configuration',
      `GOOGLE_CLOUD_PROJECT=${options?.projectId || 'your-gcp-project-id'}`,
      `GOOGLE_CLOUD_LOCATION=${options?.location || 'global'}`,
    ].join('\n');

    const readmeCode = [
      `# ${workflow.name || 'Visual Agent Designer - LangGraph Project'}`,
      '',
      'Generated with Python LangGraph.',
      '',
      '## Setup',
      '```bash',
      'python -m venv venv',
      'source venv/bin/activate',
      'pip install -r requirements.txt',
      'cp .env.example .env',
      '```',
    ].join('\n');

    return [
      { path: 'tools.py', content: toolsCode, language: 'python' },
      { path: 'agent_workflow.py', content: workflowCode, language: 'python' },
      { path: 'requirements.txt', content: requirementsCode, language: 'text' },
      { path: '.env.example', content: envCode, language: 'text' },
      { path: 'README.md', content: readmeCode, language: 'markdown' },
    ];
  }
}
