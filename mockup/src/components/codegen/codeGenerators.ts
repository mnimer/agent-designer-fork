  return [
    { name: 'graph.py', language: 'python', content: graphPy, description: 'LangGraph StateGraph definition and execution loop' },
    { name: 'state.py', language: 'python', content: statePy, description: 'TypedDict state & memory schema' },
    { name: 'requirements.txt', language: 'python', content: reqTxt, description: 'LangGraph & LangChain dependencies' },
    { name: 'README.md', language: 'markdown', content: readmeMd, description: 'LangGraph execution documentation' },
  ];
